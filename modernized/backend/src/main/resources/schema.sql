-- Schema mirroring the Db2 DDL in base/cntl/db2cre.jcl (H2 dialect).
CREATE TABLE IF NOT EXISTS customer (
  customerNumber INTEGER GENERATED BY DEFAULT AS IDENTITY(START WITH 1000001) PRIMARY KEY,
  firstName      VARCHAR(10),
  lastName       VARCHAR(20),
  dateOfBirth    DATE,
  houseName      VARCHAR(20),
  houseNumber    VARCHAR(4),
  postcode       VARCHAR(8),
  phonehome      VARCHAR(20),
  phonemobile    VARCHAR(20),
  emailaddress   VARCHAR(100)
);

CREATE TABLE IF NOT EXISTS customer_secure (
  customerNumber  INTEGER PRIMARY KEY REFERENCES customer(customerNumber) ON DELETE CASCADE,
  customerPass    VARCHAR(32),
  state_indicator VARCHAR(1),
  pass_changes    INTEGER
);

CREATE TABLE IF NOT EXISTS policy (
  policyNumber     INTEGER GENERATED BY DEFAULT AS IDENTITY(START WITH 1000001) PRIMARY KEY,
  customerNumber   INTEGER NOT NULL REFERENCES customer(customerNumber) ON DELETE CASCADE,
  issueDate        DATE,
  expiryDate       DATE,
  policyType       VARCHAR(1),
  lastChanged      TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  brokerId         INTEGER,
  brokersReference VARCHAR(10),
  payment          INTEGER,
  commission       SMALLINT
);

CREATE TABLE IF NOT EXISTS endowment (
  policyNumber INTEGER PRIMARY KEY REFERENCES policy(policyNumber) ON DELETE CASCADE,
  equities     VARCHAR(1),
  withProfits  VARCHAR(1),
  managedFund  VARCHAR(1),
  fundName     VARCHAR(10),
  term         SMALLINT,
  sumAssured   INTEGER,
  lifeAssured  VARCHAR(31),
  paddingData  VARCHAR(32606)
);

CREATE TABLE IF NOT EXISTS house (
  policyNumber INTEGER PRIMARY KEY REFERENCES policy(policyNumber) ON DELETE CASCADE,
  propertyType VARCHAR(15),
  bedrooms     SMALLINT,
  value        INTEGER,
  houseName    VARCHAR(20),
  houseNumber  VARCHAR(4),
  postcode     VARCHAR(8)
);

CREATE TABLE IF NOT EXISTS motor (
  policyNumber      INTEGER PRIMARY KEY REFERENCES policy(policyNumber) ON DELETE CASCADE,
  make              VARCHAR(15),
  model             VARCHAR(15),
  value             INTEGER,
  regNumber         VARCHAR(7),
  colour            VARCHAR(8),
  cc                SMALLINT,
  yearOfManufacture DATE,
  premium           INTEGER,
  accidents         INTEGER
);

CREATE TABLE IF NOT EXISTS commercial (
  policyNumber    INTEGER PRIMARY KEY REFERENCES policy(policyNumber) ON DELETE CASCADE,
  requestDate     TIMESTAMP,
  startDate       DATE,
  renewalDate     DATE,
  address         VARCHAR(255),
  zipcode         VARCHAR(8),
  latitudeN       VARCHAR(11),
  longitudeW      VARCHAR(11),
  customer        VARCHAR(255),
  propertyType    VARCHAR(255),
  firePeril       SMALLINT,
  firePremium     INTEGER,
  crimePeril      SMALLINT,
  crimePremium    INTEGER,
  floodPeril      SMALLINT,
  floodPremium    INTEGER,
  weatherPeril    SMALLINT,
  weatherPremium  INTEGER,
  status          SMALLINT,
  rejectionReason VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS claim (
  claimNumber  INTEGER GENERATED BY DEFAULT AS IDENTITY(START WITH 1000001) PRIMARY KEY,
  policyNumber INTEGER NOT NULL REFERENCES policy(policyNumber) ON DELETE CASCADE,
  claimDate    DATE,
  paid         INTEGER,
  value        INTEGER,
  cause        VARCHAR(255),
  observations VARCHAR(255)
);
